// Writes seed-accounts.sql: one row per starter staff account, with the
// starter password already hashed. Hashing happens here, on your computer,
// so the Worker never spends its time on it.
//
//   node scripts/make-accounts.mjs            → uses the default password
//   node scripts/make-accounts.mjs MyPass123  → uses your own

import { pbkdf2Sync, randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { DEFAULT_SETTINGS, DEFAULT_STAFF } from "../src/lib/seed.js";

const password = process.argv[2] || process.env.TLA_STARTER_PASSWORD || "";
if (!password) {
  console.error("Give the starter password as an argument, or set TLA_STARTER_PASSWORD.");
  console.error("  node scripts/make-accounts.mjs <password>");
  process.exit(1);
}
const ROUNDS = 100000; // must match src/lib/security.js, and Workers caps it here

const hash = (plain) => {
  const salt = randomBytes(16);
  const key = pbkdf2Sync(plain, salt, ROUNDS, 32, "sha256");
  return `pbkdf2$${ROUNDS}$${salt.toString("base64")}$${key.toString("base64")}`;
};

const esc = (s) => String(s).replace(/'/g, "''");
const domain = DEFAULT_SETTINGS.staffDomain;

const rows = DEFAULT_STAFF.map((s, i) => {
  const email = `${s.username}@${domain}`;
  return `INSERT OR IGNORE INTO employees (id, email, name, phone, title, department, role, password_hash, must_change, hired_on)
VALUES ('emp_${s.username}', '${esc(email)}', '${esc(s.name)}', '', '${esc(s.title)}', '${s.department}', '${s.role}', '${hash(password)}', 1, date('now'));`;
});

const sql = `-- Starter staff accounts for Twins Locs Arena.
-- Everyone signs in with their username (for example: owner) or the full
-- address (owner@${domain}) and the starter password. Each person is asked to
-- change it the first time they sign in.
--
-- Generated by scripts/make-accounts.mjs - re-run it to rotate the password.

${rows.join("\n\n")}

INSERT OR REPLACE INTO settings (key, value) VALUES ('staffDomain', '"${domain}"');
`;

writeFileSync(new URL("../seed-accounts.sql", import.meta.url), sql);
console.log(`Wrote seed-accounts.sql with ${DEFAULT_STAFF.length} accounts.`);
console.log(`Sign in with: ${DEFAULT_STAFF.map((s) => s.username).join(", ")}`);
console.log("Starter password: the one you just passed in. Write it down; it is not stored anywhere here.");
